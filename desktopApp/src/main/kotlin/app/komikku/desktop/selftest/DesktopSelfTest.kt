import app.komikku.desktop.extension.LoadedExtension
import uy.kohesive.injekt.Injekt
import java.io.Closeable
import java.io.File
import java.net.URI
import java.nio.charset.Charset
import java.nio.file.FileSystems
import java.nio.file.Files
import java.security.KeyPairGenerator
import java.security.Signature
import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.util.Locale
import java.util.zip.ZipFile
import javax.crypto.KeyAgreement
import javax.net.ssl.SSLContext

/**
 * KMK (M2): a headless self-test of the packaged app, `Komikku --self-test[=<report file>]`, for what the full JDK of
 * `./gradlew :desktopApp:run` and the tests hides: the bundled (jlink'd) runtime's modules and the native libraries
 * inside the app's jars. The first macOS test build could not install any APK extension (the runtime lacked
 * `jdk.zipfs`, which dex2jar writes the converted jar with); `build_desktop.yml` now runs this against the packaged
 * launcher on every OS.
 *
 * `--self-test-extensions=<folder>` adds one check per extension APK in the folder: converted, loaded and every class
 * verified inside the packaged runtime (CI passes real Keiyoushi extensions; their classes failed the verifier in the
 * second macOS test build while the fixture passed).
 *
 * Deterministic and offline: temporary files only, no network, no window, no data folder (the extension checks build
 * the app's object graph over a temporary one). Prints one line per check
 * and writes the same lines to the report file when one is given (the Windows launcher has no console); the last line
 * is [PASSED] or [FAILED]. [main] exits with 0 only when every check passed.
 */
object DesktopSelfTest {

    const val ARGUMENT = "--self-test"
    const val EXTENSIONS_ARGUMENT = "--self-test-extensions"
    const val PASSED = "SELF-TEST PASSED"
    const val FAILED = "SELF-TEST FAILED"

    /** The bundled runtime's module list (desktopApp/runtime-modules.txt, copied into the resources by the build). */
    const val MODULES_RESOURCE = "/app/komikku/desktop/selftest/runtime-modules.txt"

    /** A signed one-source extension APK with dex code (regenerated by `SelfTestFixtureWriter` in :desktop:extension-runtime). */
    const val EXTENSION_RESOURCE = "/app/komikku/desktop/selftest/selftest-extension.apk"
    const val EXTENSION_SOURCE_ID = 4243L

    private const val MISSING_LISTED = 3

    class Check(val name: String, val run: (File) -> String)

    data class Outcome(val name: String, val error: Throwable?, val detail: String) {
        val passed: Boolean get() = error == null
        override fun toString(): String = if (error == null) "OK   $name: $detail" else "FAIL $name: $error"
    }

    /** Whether [args] ask for the self-test; the report file after `=`, if any, is [reportFile]. */
    fun isRequested(args: Array<String>): Boolean = args.any { it == ARGUMENT || it.startsWith("$ARGUMENT=") }

    fun reportFile(args: Array<String>): File? = args.firstOrNull { it.startsWith("$ARGUMENT=") }
        ?.substringAfter('=')
        ?.takeIf { it.isNotBlank() }
        ?.let(::File)

    /** The module names in [text] (runtime-modules.txt's format: one per line, `#` comments). */
    fun parseModules(text: String): List<String> = text.lineSequence()
        .map { it.substringBefore('#').trim() }
        .filter { it.isNotEmpty() }
        .toList()

    val checks: List<Check> = listOf(
        Check("runtime modules") {
            val listed = parseModules(resourceText(MODULES_RESOURCE))
            check(listed.isNotEmpty()) { "the module list is empty" }
            val missing = listed.filterNot { ModuleLayer.boot().findModule(it).isPresent }
            check(missing.isEmpty()) { "missing from the runtime: ${missing.joinToString()}" }
            "${listed.size} listed, all present"
        },
        Check("zip file system") { dir ->
            val zip = File(dir, "zipfs.zip")
            FileSystems.newFileSystem(URI.create("jar:${zip.toURI()}"), mapOf("create" to "true")).use { fs ->
                Files.writeString(fs.getPath("entry.txt"), "komikku")
            }
            val text = ZipFile(zip).use { it.getInputStream(it.getEntry("entry.txt")).readBytes().decodeToString() }
            check(text == "komikku") { "read back '$text'" }
            "written and read back"
        },
        Check("APK extension (dex2jar)") { dir ->
            val apk = File(dir, "selftest-extension.apk")
            apk.outputStream().use { out -> resourceStream(EXTENSION_RESOURCE).use { it.copyTo(out) } }
            // The fixture has branching methods and an R8-style inlined constructor (the second Mac test build
            // failed with "Expecting a stackmap frame" on real extensions); every class must pass the verifier
            checkExtension(apk, dir, strict = true) { loaded ->
                val ids = loaded.sources.map { it.id }
                check(ids == listOf(EXTENSION_SOURCE_ID)) { "sources $ids" }
            }
        },
        Check("EC crypto (TLS)") {
            val keys = KeyPairGenerator.getInstance("EC").apply { initialize(256) }.generateKeyPair()
            val data = "komikku".toByteArray()
            val signature = Signature.getInstance("SHA256withECDSA").apply {
                initSign(keys.private)
                update(data)
            }.sign()
            val verified = Signature.getInstance("SHA256withECDSA").apply {
                initVerify(keys.public)
                update(data)
            }.verify(signature)
            check(verified) { "ECDSA signature not verified" }
            KeyAgreement.getInstance("ECDH")
            KeyPairGenerator.getInstance("X25519").generateKeyPair()
            val suites = SSLContext.getDefault().supportedSSLParameters.cipherSuites
            check(suites.any { it.startsWith("TLS_ECDHE_") }) { "no ECDHE cipher suite" }
            "EC / ECDSA / ECDH / X25519, ${suites.count { it.startsWith("TLS_ECDHE_") }} ECDHE suites"
        },
        Check("charsets") {
            val samples = mapOf(
                "Shift_JIS" to "漫画",
                "EUC-JP" to "漫画",
                "GBK" to "漫画",
                "GB18030" to "漫画",
                "Big5" to "漫畫",
                "EUC-KR" to "만화",
                "windows-1251" to "манга",
            )
            for ((name, text) in samples) {
                val charset = Charset.forName(name)
                val back = String(text.toByteArray(charset), charset)
                check(back == text) { "$name round trip gave '$back'" }
            }
            samples.keys.joinToString()
        },
        Check("locale data") {
            val month = DateTimeFormatter.ofPattern("MMMM", Locale.JAPANESE).format(LocalDate.of(2024, 1, 1))
            check(month == "1月") { "Japanese January is '$month'" }
            val french = DateTimeFormatter.ofPattern("MMMM", Locale.FRENCH).format(LocalDate.of(2024, 2, 1))
            check(french == "février") { "French February is '$french'" }
            "ja '$month', fr '$french'"
        },
        Check("SQLite (bundled native library)") {
            BundledSQLiteDriver().open(":memory:").use { connection ->
                connection.prepare("SELECT sqlite_version()").use { statement ->
                    check(statement.step()) { "no row" }
                    "SQLite ${statement.getText(0)}"
                }
            }
        },
        Check("QuickJS (native library)") {
            QuickJs.create().use { js ->
                val result = js.evaluate("[1, 2, 3].map(x => x * 2).join(',')")
                check(result == "2,4,6") { "evaluated to $result" }
                "evaluated '$result'"
            }
        },
    )

    /**
     * Converts and loads the extension [apk] in [dir] like the app does, then loads and links every class of the
     * converted jar, which runs the JVM's verifier on all of them (not only on the classes the sources need). Fails
     * when a class is rejected, an untranslated method is left, or (when [strict]) a class refers to a class the
     * desktop lacks; else the latter are listed in the result. [more] checks the loaded extension further.
     */
    fun checkExtension(apk: File, dir: File, strict: Boolean, more: (LoadedExtension) -> Unit = {}): String {
        val runtime = ExtensionRuntime(File(dir, "extensions"))
        val inspected = runtime.inspect(apk)
        check(inspected is ExtensionPackageResult.Valid) { "not a valid extension: $inspected" }
        val loaded = runtime.load(inspected.extension)
        try {
            check(loaded.failedMethods.isEmpty()) { "untranslated methods ${loaded.failedMethods}" }
            check(loaded.sources.isNotEmpty()) { "no sources" }
            more(loaded)
            val verification = ExtensionRuntime.verifyClasses(loaded.jar)
            check(verification.rejected.isEmpty()) {
                "${verification.rejected.size} class(es) fail verification, first: ${verification.rejected.first()}"
            }
            check(!strict || verification.unresolved.isEmpty()) { "unresolved classes ${verification.unresolved}" }
            val unresolved = verification.unresolved.takeIf { it.isNotEmpty() }?.let { classes ->
                val missing = classes.map { it.substringAfter(": ") }.distinct()
                ", ${classes.size} refer to classes the desktop lacks (${missing.take(MISSING_LISTED).joinToString()}" +
                    (if (missing.size > MISSING_LISTED) ", …)" else ")")
            }.orEmpty()
            val names = loaded.sources.map { it.name }.distinct().joinToString { "'$it'" }
            return "${inspected.extension.pkgName} ${inspected.extension.versionName}: ${loaded.sources.size} source(s) " +
                "$names, ${verification.verified} classes verified$unresolved"
        } finally {
            (loaded.classLoader as? Closeable)?.close()
        }
    }

    /** `--self-test-extensions=<folder>`: extension APKs to check as well ([extensionChecks]). */
    fun extensionsDir(args: Array<String>): File? = args.firstOrNull { it.startsWith("$EXTENSIONS_ARGUMENT=") }
        ?.substringAfter('=')
        ?.takeIf { it.isNotBlank() }
        ?.let(::File)

    /**
     * One check per `.apk` in [dir] ([checkExtension]); a check that fails when [dir] has none. Real extensions resolve
     * the app's objects from Injekt when their sources are created (`Injekt.get<Application>()`, the network helper),
     * so the checks first build the app's graph ([DesktopInjekt]) over a temporary data folder, unless one is there.
     */
    fun extensionChecks(dir: File): List<Check> {
        val apks = dir.listFiles { file -> file.isFile && file.extension == "apk" }.orEmpty().sortedBy { it.name }
        if (apks.isEmpty()) return listOf(Check("extensions in $dir") { error("no .apk files") })
        return apks.map { apk ->
            Check("extension ${apk.name}") { work ->
                ensureAppGraph()
                checkExtension(apk, work, strict = false)
            }
        }
    }

    /** Builds the app's Injekt graph over a temporary data folder (deleted on exit) when no application is registered. */
    @Synchronized
    private fun ensureAppGraph() {
        if (Injekt.getInstanceOrNull<Application>(Application::class.java) != null) return
        val dataDir = Files.createTempDirectory("komikku-selftest-data").toFile()
        Runtime.getRuntime().addShutdownHook(Thread { dataDir.deleteRecursively() })
        DesktopInjekt.init(dataDir)
    }

    /** Runs every check (each in its own temporary folder, deleted afterwards). */
    fun run(extra: List<Check> = emptyList()): List<Outcome> = (checks + extra).map { check ->
        val dir = Files.createTempDirectory("komikku-selftest").toFile()
        try {
            Outcome(check.name, null, check.run(dir))
        } catch (e: Throwable) {
            Outcome(check.name, e, "")
        } finally {
            dir.deleteRecursively()
        }
    }

    /**
     * Runs the checks (with the APKs in [extensions], if given), prints them (and writes them to [report]); returns
     * the exit code.
     */
    fun main(report: File?, extensions: File? = null): Int {
        val outcomes = run(extensions?.let(::extensionChecks).orEmpty())
        val runtime = "Java ${System.getProperty("java.runtime.version")} (${System.getProperty("java.home")}), " +
            "${System.getProperty("os.name")} ${System.getProperty("os.arch")}"
        val lines = listOf("Komikku self-test, $runtime") + outcomes.map { it.toString() } +
            (if (outcomes.all { it.passed }) PASSED else FAILED)
        lines.forEach(::println)
        outcomes.forEach { it.error?.printStackTrace() }
        report?.let { file ->
            file.absoluteFile.parentFile?.mkdirs()
            file.writeText(lines.joinToString("\n", postfix = "\n"))
        }
        return if (outcomes.all { it.passed }) 0 else 1
    }

    private fun resourceStream(path: String) =
        DesktopSelfTest::class.java.getResourceAsStream(path) ?: error("resource $path missing")

    private fun resourceText(path: String): String = resourceStream(path).use { it.readBytes().decodeToString() }
}
